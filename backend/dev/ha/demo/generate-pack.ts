/**
 * Writes demo/pack.yaml: extra template switches and lights that remember their last state
 * that fill the rooms the built-in `demo` integration leaves thin. Run: bun dev/ha/demo/generate-pack.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

export const SWITCHES = [
  ["Coffee machine", "Kitchen"], ["Dishwasher", "Kitchen"], ["Kettle", "Kitchen"],
  ["Towel rail", "Bathroom"], ["Washing machine", "Bathroom"],
  ["Garden sprinklers", "Garden"], ["Pool pump", "Garden"],
  ["Desk fan plug", "Arjun's room"], ["Gaming console", "Arjun's room"],
  ["Hall heater", "Hall"], ["Bedroom heater", "Bedroom"], ["Soundbar", "Living room"],
] as const;
export const LIGHTS = [
  ["Dining lights", "Living room"], ["Shelf lights", "Living room"],
  ["Under-cabinet lights", "Kitchen"], ["Island lights", "Kitchen"],
  ["Wardrobe light", "Bedroom"], ["Reading lamp", "Bedroom"],
  ["Desk lamp", "Arjun's room"], ["Star projector", "Arjun's room"],
  ["Mirror light", "Bathroom"], ["Shower light", "Bathroom"],
  ["Bed lamp", "Guest room"],
  ["Porch light", "Garden"], ["Path lights", "Garden"], ["Patio lights", "Garden"],
  ["Stair light", "Hall"],
] as const;

export const slug = (n: string) => n.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
// No state template: the entity remembers what it was last told (so no helper entities show up in the app as duplicates).
const nothing = "[{delay: \"00:00:00\"}]";

let y = "# Generated by generate-pack.ts. Extra demo devices (they remember what they were last told).\ntemplate:\n  - switch:\n";
for (const [n] of SWITCHES) y += `      - name: ${n}\n        unique_id: demo_${slug(n)}\n        turn_on: ${nothing}\n        turn_off: ${nothing}\n`;
y += "  - light:\n";
for (const [n] of LIGHTS) y += `      - name: ${n}\n        unique_id: demo_${slug(n)}\n        set_level: ${nothing}\n        turn_on: ${nothing}\n        turn_off: ${nothing}\n`;
if (import.meta.main) {
  writeFileSync(join(import.meta.dir, "pack.yaml"), y);
  console.log(`Wrote ${SWITCHES.length} switches and ${LIGHTS.length} lights.`);
}
