#!/usr/bin/env python3
"""Regenerate the Alice wordmark used by the launch screen.

The mark is the web app's `.brand` (Bricolage Grotesque, weight 800, width 78%,
optical size 40, tracking -0.035em) outlined from the same font shipped with the
app, so the system splash and the Compose loading screen can draw the exact same
geometry. Re-run this only when the brand or the font changes.

    pip install fonttools uharfbuzz
    python3 android/tools/gen_wordmark.py
"""
import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ANDROID = Path(__file__).resolve().parents[1]
SRC = ANDROID / "app/src/main/res/font/bricolage_grotesque.ttf"

SIZE = 192          # Android splash icon box, in dp
MARK_WIDTH = 112.0  # ink width of "alice." in dp
TRACKING = -0.035   # em, same as `.brand`
LIGHT = ("#1E241F", "#E9B949")
DARK = ("#EEE8DB", "#F0C65A")


def build_paths():
    font = TTFont(SRC)
    inst = instantiateVariableFont(
        font, {"wght": 800, "wdth": 78, "opsz": 40}, inplace=False, updateFontNames=False
    )
    buf = io.BytesIO()
    inst.save(buf)

    face = hb.Face(buf.getvalue())
    hbfont = hb.Font(face)
    upem = face.upem
    glyph_set = inst.getGlyphSet()
    order = inst.getGlyphOrder()

    def shape(text):
        b = hb.Buffer()
        b.add_str(text)
        b.guess_segment_properties()
        hb.shape(hbfont, b, {"kern": True, "liga": True})
        return b.glyph_infos, b.glyph_positions

    infos, positions = shape("alice")
    x = 0.0
    placed = []
    for info, pos in zip(infos, positions):
        placed.append((order[info.codepoint], x + pos.x_offset))
        x += pos.x_advance + TRACKING * upem

    dot_infos, dot_positions = shape(".")
    dot_name = order[dot_infos[0].codepoint]
    dot_x = x + dot_positions[0].x_offset

    def outline(name, dx):
        pen = SVGPathPen(glyph_set)
        glyph_set[name].draw(TransformPen(pen, Transform(1, 0, 0, -1, dx, 0)))
        return pen.getCommands()

    def bounds(name, dx):
        pen = BoundsPen(glyph_set)
        glyph_set[name].draw(TransformPen(pen, Transform(1, 0, 0, -1, dx, 0)))
        return pen.bounds

    ink = " ".join(outline(name, dx) for name, dx in placed)
    glow = outline(dot_name, dot_x)

    all_bounds = [bounds(name, dx) for name, dx in placed] + [bounds(dot_name, dot_x)]
    x0, y0 = min(b[0] for b in all_bounds), min(b[1] for b in all_bounds)
    x1, y1 = max(b[2] for b in all_bounds), max(b[3] for b in all_bounds)

    scale = MARK_WIDTH / (x1 - x0)
    tx = (SIZE - (x1 - x0) * scale) / 2 - x0 * scale
    ty = (SIZE - (y1 - y0) * scale) / 2 - y0 * scale
    return ink, glow, scale, tx, ty, (y1 - y0) * scale


def vector(ink_color, glow_color, ink, glow, scale, tx, ty):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_wordmark.py from bricolage_grotesque.ttf (wght 800, wdth 78, opsz 40).
     The system splash and the in-app loading screen share this mark, so the handoff is invisible. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{SIZE}dp"
    android:height="{SIZE}dp"
    android:viewportWidth="{SIZE}"
    android:viewportHeight="{SIZE}">
    <group
        android:scaleX="{scale:.6f}"
        android:scaleY="{scale:.6f}"
        android:translateX="{tx:.4f}"
        android:translateY="{ty:.4f}">
        <path
            android:fillColor="{ink_color}"
            android:pathData="{ink}" />
        <path
            android:fillColor="{glow_color}"
            android:pathData="{glow}" />
    </group>
</vector>
'''


def main():
    ink, glow, scale, tx, ty, _ = build_paths()
    targets = {
        ANDROID / "app/src/main/res/drawable/ic_splash_wordmark.xml": LIGHT,
        ANDROID / "app/src/main/res/drawable-night/ic_splash_wordmark.xml": DARK,
    }
    for path, (ink_color, glow_color) in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(vector(ink_color, glow_color, ink, glow, scale, tx, ty))
        print(path.relative_to(ANDROID))


if __name__ == "__main__":
    main()
